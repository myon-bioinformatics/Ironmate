"""Regenerate the browser's PPTX package shell with the existing pinned JS writer.

Only generated XML data is retained. No third-party JS runs in the browser.
"""
import json
import re
import subprocess
import tempfile
from pathlib import Path
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]


def shell_script():
    with tempfile.TemporaryDirectory() as directory:
        spec, deck = Path(directory) / 'spec.json', Path(directory) / 'shell.pptx'
        spec.write_text(json.dumps({'width': 10, 'height': 5.625, 'slides': [{}]}))
        subprocess.run(['node', str(ROOT / 'scripts/pptxgen_render.mjs'), str(spec), str(deck)],
                       cwd=ROOT, check=True, capture_output=True, timeout=60)
        with ZipFile(deck) as archive:
            parts = {}
            for name in sorted(archive.namelist()):
                if name.endswith('/') or name.startswith('ppt/slides/'):
                    continue
                text = archive.read(name).decode('utf-8')
                text = re.sub(r'(<dcterms:(?:created|modified)[^>]*>)[^<]+',
                              r'\g<1>2000-01-01T00:00:00Z', text)
                parts[name] = text
    data = json.dumps(parts, ensure_ascii=True, separators=(',', ':'))
    return ('/* Generated by scripts/build_slide_shell.py using locked PptxGenJS 4.0.1. */\n'
            '(function(root){const parts=' + data + ';'
            'if(typeof module==="object")module.exports=parts;else root.IronmateSlideShell=parts;'
            '})(globalThis);\n')


if __name__ == '__main__':
    (ROOT / 'studio/slides/package.js').write_text(shell_script(), encoding='utf-8')
