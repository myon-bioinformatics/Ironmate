"""web-ui JSON -> Mermaid Markdown, SVG, PNG, standard Base64 or PNG data URI.

JSON validation and diagram generation belong to the locked web-ui source.
This adapter only renders it; it never installs tools or contacts a service.
"""
from __future__ import annotations

import argparse
import json
import math
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from xml.etree import ElementTree as ET

from vendor.web_ui_flow import MAX_INPUT, flow_mermaid, validate
from mermaid_svg import render_mermaid
from image_studio import raster_svg, _png_output

FORMATS = ('mermaid', 'svg', 'png', 'base64', 'data-uri')
MAX_SVG = 32 * 1024 * 1024


def read_spec(raw):
    """Bound UTF-8 bytes before parsing, for files, stdin and both language APIs."""
    if not isinstance(raw, bytes) or len(raw) > MAX_INPUT:
        raise ValueError('flow JSON must be UTF-8 bytes, at most 256KiB')
    return validate(json.loads(raw.decode('utf-8')))


def _sized_svg(svg, scale):
    """Use Mermaid's intrinsic viewBox, preserving its vector layout and XML."""
    if len(svg) > MAX_SVG:
        raise ValueError('rendered SVG exceeds 32MiB')
    root = ET.fromstring(svg)
    if root.tag != '{http://www.w3.org/2000/svg}svg':
        raise ValueError('renderer must return an SVG document')
    box = [float(x) for x in re.split(r'[\s,]+', root.attrib.get('viewBox', '').strip())]
    if len(box) != 4 or not all(math.isfinite(x) for x in box) or min(box[2:]) <= 0:
        raise ValueError('renderer must return a finite positive viewBox')
    width, height = math.ceil(box[2] * scale), math.ceil(box[3] * scale)
    if not (1 <= width <= 8192 and 1 <= height <= 8192 and width * height <= 16777216):
        raise ValueError('output must be each side <=8192px and <=16MP; reduce scale')
    # Avoid reserializing foreignObject XHTML or changing Mermaid's namespaces.
    text = svg.decode('utf-8')
    match = re.search(r'<svg\b[^>]*>', text)
    if not match:
        raise ValueError('renderer must return an SVG root')
    tag = re.sub(r'\s(?:width|height|style)="[^"]*"', '', match.group())
    # Background is generated by mmdc. Preserve it while removing max-width,
    # which would otherwise silently cap scaled output in inline browser views.
    style = root.attrib.get('style', '')
    style = ';'.join(part for part in style.split(';') if part.strip() and not part.strip().lower().startswith('max-width:'))
    from html import escape
    tag = tag[:-1] + f' width="{width}" height="{height}" style="{escape(style, quote=True)}">'
    return (text[:match.start()] + tag + text[match.end():]).encode('utf-8')


def render_flow(spec, format='svg', *, scale=1, background=None, mmdc='mmdc',
                chrome=None, puppeteer_config=None):
    """Return bytes. None background means transparent; otherwise #RRGGBB.

    Mermaid needs Python only. SVG additionally needs local mmdc and its browser;
    PNG/Base64/data-uri additionally need Node 22+ and local Chrome/Chromium.
    Fonts are host supplied. No fallback produces a different format on failure.
    """
    if format not in FORMATS:
        raise ValueError('unsupported flow output format')
    if type(scale) not in (int, float) or not math.isfinite(scale) or not .25 <= scale <= 8:
        raise ValueError('scale must be finite and between 0.25 and 8')
    if background is not None and (not isinstance(background, str) or not re.fullmatch(r'#[0-9a-fA-F]{6}', background)):
        raise ValueError('background must be #RRGGBB or None')
    # Enforce the byte budget for Python callers as well as CLI/Node callers.
    spec = read_spec(json.dumps(spec, ensure_ascii=False, allow_nan=False).encode('utf-8'))
    markdown = flow_mermaid(spec)
    if format == 'mermaid':
        return markdown.encode('utf-8')
    with tempfile.TemporaryDirectory(prefix='ironmate-flow-') as temp:
        directory = Path(temp)
        config = directory / 'config.json'
        # Plain SVG text stays usable in image viewers and Canvas (no XHTML).
        config.write_text(json.dumps({'securityLevel': 'strict', 'htmlLabels': False,
                                     'flowchart': {'htmlLabels': False},
                                     'deterministicIds': True, 'deterministicIDSeed': 'ironmate-flow'}))
        _, paths = render_mermaid(markdown, directory, mmdc=mmdc, background=background,
                                  config=config, puppeteer_config=puppeteer_config)
        if len(paths) != 1:
            raise RuntimeError('expected exactly one rendered flow')
        with paths[0].open('rb') as handle:
            svg = _sized_svg(handle.read(MAX_SVG + 1), scale)
    if format == 'svg':
        return svg
    return _png_output(raster_svg(svg, chrome=chrome), 'png' if format == 'png' else 'base64',
                       data_uri=format == 'data-uri')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('input', nargs='?', type=Path, help='JSON file (default: stdin)')
    parser.add_argument('--format', choices=FORMATS, default='svg')
    parser.add_argument('--scale', type=float, default=1)
    parser.add_argument('--background', help='#RRGGBB (default: transparent)')
    parser.add_argument('--mmdc', default='mmdc')
    parser.add_argument('--chrome')
    parser.add_argument('--puppeteer-config', type=Path, help='optional local mmdc browser configuration')
    parser.add_argument('-o', '--output', type=Path)
    parser.add_argument('--force', action='store_true')
    args = parser.parse_args(argv)
    try:
        if args.input:
            with args.input.open('rb') as handle:
                spec = read_spec(handle.read(MAX_INPUT + 1))
        else:
            spec = read_spec(sys.stdin.buffer.read(MAX_INPUT + 1))
        data = render_flow(spec, args.format, scale=args.scale, background=args.background,
                           mmdc=args.mmdc, chrome=args.chrome, puppeteer_config=args.puppeteer_config)
        if args.output:
            from grid_output import write_output
            write_output(str(args.output), data, args.force)
        else:
            sys.stdout.buffer.write(data)
    except (OSError, ValueError, RuntimeError, subprocess.TimeoutExpired, ET.ParseError) as exc:
        parser.exit(2, f'flow export: {exc}\n')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
