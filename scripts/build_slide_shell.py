"""Regenerate the PPTX package shell region of STUDIO_JS in ironlib/studio_bundle.py with the existing pinned JS writer.

Only generated XML data is retained. No third-party JS runs in the browser.
"""
import json, re, subprocess, tempfile
from pathlib import Path; from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]


def shell_script():
    with tempfile.TemporaryDirectory() as directory:
        spec, deck = Path(directory) / 'spec.json', Path(directory) / 'shell.pptx'
        spec.write_text(json.dumps({'width': 10, 'height': 5.625, 'slides': [{}]}))
        subprocess.run(['node', str(ROOT / 'scripts/pptxgen_render.mjs'), str(spec), str(deck)],
                       cwd=ROOT, check=True, capture_output=True, timeout=60)
        with ZipFile(deck) as archive:
            parts = {}
            for name in sorted(archive.namelist()):
                if name.endswith('/') or name.startswith('ppt/slides/'):
                    continue
                text = archive.read(name).decode('utf-8')
                text = re.sub(r'(<dcterms:(?:created|modified)[^>]*>)[^<]+',
                              r'\g<1>2000-01-01T00:00:00Z', text)
                parts[name] = text
    data = json.dumps(parts, ensure_ascii=True, separators=(',', ':'))
    return (f'{START} Generated by scripts/build_slide_shell.py using locked PptxGenJS 4.0.1. Do not edit by hand. */\n'
            f'const IronmateSlideShell = {data};\n{END}\n')


START, END = '/* <slide-shell>', '/* </slide-shell> */'
SCRIPT = ROOT / 'ironlib/studio_bundle.py'


def shell_region(text=None):
    """The generated region of STUDIO_JS in ironlib/studio_bundle.py, from the START marker through the END marker and its newline."""
    text = SCRIPT.read_text(encoding='utf-8') if text is None else text
    start = text.index(START)
    return text[start:text.index(END, start) + len(END) + 1]


def write_shell():
    text = SCRIPT.read_text(encoding='utf-8')
    SCRIPT.write_text(text.replace(shell_region(text), shell_script()), encoding='utf-8')


if __name__ == '__main__':
    write_shell()
